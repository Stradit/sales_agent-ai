"""Build the Alembic baseline (migrations/sql/0001_baseline.sql) from the CURRENT startup schema code.

    python scripts/build_schema_baseline.py            # writes migrations/sql/0001_baseline.sql
    python scripts/build_schema_baseline.py --check    # rebuild and compare with the committed file

Creates a throwaway database on the server in DATABASE_URL (.env), runs exactly the code that used
to shape the schema at app startup (db/create_tables + the CRM, deals, copilot and search
ensure_schema functions) twice — the second run proves it is idempotent — dumps the schema, and
drops the throwaway database. The result is what "version 0001" means; see docs/DB_DEPLOYMENT_PLAN.md.
Needs pg_dump 18 on PATH or PG_BIN set.
"""
import argparse
import difflib
import os
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "migrations" / "sql" / "0001_baseline.sql"
MANIFEST = ROOT / "migrations" / "sql" / "0001_baseline.columns.txt"   # table.column type — used to verify before stamping
PG_BIN = os.environ.get("PG_BIN", r"C:\Program Files\PostgreSQL\18\bin" if os.name == "nt" else "")

# Runs inside a child process whose DATABASE_URL points at the throwaway database
STARTUP_SCHEMA = """
import os
os.environ.setdefault("COPILOT_AUTOSYNC", "0"); os.environ.setdefault("CRM_BACKGROUND", "0")
from db.create_tables import ensure_schema_compatibility
from apps.sales_crm import api as crm
from apps.sales_deals import api as deals
from apps.sales_copilot import ingest
from apps.sales_search import api as search
# Dependency order: core ORM tables, then copilot, deals (references accounts), CRM (references deals), search.
# (At app boot the order is copilot → deals → crm → search → core, with errors swallowed: a brand-new
#  database only ends up complete after a second boot. The baseline removes that dependence.)
from apps.sales_copilot import pipeline
from apps.sales_crm import demo_seed
from db.connection import engine
from sqlalchemy import text
for _ in range(2):
    ensure_schema_compatibility()
    ingest.ensure_schema(); deals.ensure_schema(); crm.ensure_schema(); search._ensure_schema()
    pipeline.ensure_table()                                   # created on first use of /copilot-pipeline
    with engine.begin() as c:
        c.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))   # search install() (typo tolerance)
        c.execute(text(demo_seed.REGISTRY_DDL))               # created by the demo seed script
# Tables owned by apps/content_pipeline (targets, run_history) are NOT part of this app's schema.
print("startup schema applied twice")
"""


def tool(name: str) -> str:
    return str(Path(PG_BIN) / name) if PG_BIN else name


def env_url() -> str:
    """A server to create the throwaway database on: DATABASE_URL from the environment (CI), else .env."""
    raw = os.environ.get("DATABASE_URL", "")
    env_file = ROOT / ".env"
    if not raw and env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("DATABASE_URL="):
                raw = line.split("=", 1)[1].strip().strip("'\"")
    if not raw:
        raise SystemExit("DATABASE_URL is not set (environment or .env)")
    return re.sub(r"^postgres(ql)?(\+[a-z0-9]+)?://", "postgresql://", raw)


def with_db(url: str, db: str) -> str:
    return re.sub(r"^([a-z]+://[^/]+/)[^?]*", rf"\g<1>{db}", url)


def clean(sql: str) -> str:
    """Drop session-specific lines pg_dump adds (they'd break the Alembic run that follows)."""
    keep = []
    for line in sql.replace("\r", "").splitlines():
        if line.startswith(("\\restrict", "\\unrestrict", "SET ", "SELECT pg_catalog.set_config(")):
            continue
        if line.startswith("-- Dumped") or line.startswith("-- Started on") or line.startswith("-- Completed on"):
            continue
        keep.append(line)
    text = "\n".join(keep)
    text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
    header = ("-- Baseline schema (Alembic revision 0001). Generated by scripts/build_schema_baseline.py from the\n"
              "-- startup schema code as of this commit. Do not edit: add a new migration instead.\n\n")
    return header + text


def build() -> tuple:
    url = env_url()
    admin = with_db(url, "postgres")
    tmp = f"schema_baseline_{int(time.time())}"
    psql = tool("psql")
    subprocess.run([psql, admin, "-qc", f'create database "{tmp}"'], check=True)
    try:
        child_env = {**os.environ, "DATABASE_URL": with_db(url, tmp), "COPILOT_AUTOSYNC": "0", "CRM_BACKGROUND": "0",
                     "CRM_NOTIFY_SUPPRESS": "1", "SEED_ADMIN_EMAIL": "", "SEED_ADMIN_PASSWORD": ""}
        r = subprocess.run([sys.executable, "-c", STARTUP_SCHEMA], cwd=ROOT, env=child_env, capture_output=True, text=True)
        print((r.stdout + r.stderr).strip()[-2000:])
        if r.returncode != 0:
            raise SystemExit("startup schema code failed on the empty database")
        dump = subprocess.run([tool("pg_dump"), "--schema-only", "--no-owner", "--no-privileges", "--no-comments",
                               "--dbname", with_db(url, tmp)], check=True, capture_output=True, text=True).stdout
        cols = subprocess.run([psql, with_db(url, tmp), "-Atc",
                               "select table_name||'.'||column_name||' '||data_type from information_schema.columns "
                               "where table_schema='public' order by 1"], check=True, capture_output=True, text=True).stdout
        rows = [ln for ln in cols.replace(chr(13), "").splitlines() if ln]
        return clean(dump), "".join(ln + chr(10) for ln in sorted(rows))
    finally:
        subprocess.run([psql, admin, "-qc", f'drop database if exists "{tmp}" with (force)'], check=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare a fresh build with the committed baseline")
    args = ap.parse_args()
    sql, manifest = build()
    if args.check:
        same = (OUT.exists() and OUT.read_text(encoding="utf-8") == sql
                and MANIFEST.exists() and MANIFEST.read_text(encoding="utf-8") == manifest)
        print("baseline matches the startup schema code" if same else "baseline DIFFERS from the startup schema code")
        if not same:   # show what differs, so a CI failure can be diagnosed from its log alone
            for path, fresh in ((OUT, sql), (MANIFEST, manifest)):
                old = path.read_text(encoding="utf-8") if path.exists() else ""
                diff = list(difflib.unified_diff(old.splitlines(), fresh.splitlines(), f"committed/{path.name}",
                                                 f"fresh/{path.name}", lineterm="", n=2))
                print("\n".join(diff[:300]) + (f"\n... {len(diff) - 300} more diff lines" if len(diff) > 300 else ""))
        sys.exit(0 if same else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding="utf-8", newline="\n")
    MANIFEST.write_text(manifest, encoding="utf-8", newline="\n")
    tables = len(re.findall(r"^CREATE TABLE ", sql, re.M))
    print(f"wrote {OUT.relative_to(ROOT)}: {tables} tables, {len(sql.splitlines())} lines; "
          f"{MANIFEST.name}: {len(manifest.splitlines())} columns")


if __name__ == "__main__":
    main()
